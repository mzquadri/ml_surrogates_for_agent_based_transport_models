print("\n  Data is CATEGORICALLY ENCODED (-1 to 9 scale)!")
print("="*80 + "\n")

# Create figure
fig, axes = plt.subplots(1, 2, figsize=(14, 5))

# Plot 1: Distribution of encoded length values (exclude -1 = missing/unknown)
ax = axes[0]
roads_with_length = length[length >= 0]
ax.hist(roads_with_length, bins=10, color='#9B59B6', edgecolor='black', alpha=0.7)
ax.set_xlabel('Encoded Length Category (0-9 scale)', fontsize=12, fontweight='bold')
ax.set_ylabel('Number of Roads', fontsize=12, fontweight='bold')
ax.set_title('Feature 5: LENGTH Distribution\n(Encoded categories, not raw meters)', fontsize=13)
ax.grid(True, alpha=0.3)
ax.text(0.02, 0.97, f'Total segments: {len(roads_with_length)}\nMean category: {roads_with_length.mean():.2f}\nMedian category: {np.median(roads_with_length):.1f}\nMax category: {roads_with_length.max():.0f}',
        transform=ax.transAxes, verticalalignment='top', horizontalalignment='left',
        bbox=dict(boxstyle='round', facecolor='#E8DAEF', alpha=0.8), fontsize=9)

# Plot 2: Length categories (based on encoded values)
ax = axes[1]
categories = ['Very Short\n(0-2)', 'Short\n(3-4)', 'Medium\n(5-6)', 'Long\n(7-9)']
counts = [
    ((length >= 0) & (length <= 2)).sum(),
    ((length >= 3) & (length <= 4)).sum(),
    ((length >= 5) & (length <= 6)).sum(),
    ((length >= 7) & (length <= 9)).sum()
]
colors = ['#E8DAEF', '#D2B4DE', '#9B59B6', '#6C3483']
bars = ax.bar(categories, counts, color=colors, edgecolor='black', linewidth=1.5)
ax.set_ylabel('Number of Roads', fontsize=12, fontweight='bold')
ax.set_title('Feature 5: Road Length Categories', fontsize=13)
ax.grid(True, alpha=0.3, axis='y')
ax.tick_params(axis='x', rotation=0)

# Add value labels on bars
for bar, count in zip(bars, counts):
    height = bar.get_height()
    ax.text(bar.get_x() + bar.get_width()/2., height,
            f'{count}\n({count/len(length[length >= 0])*100:.1f}%)',
            ha='center', va='bottom', fontweight='bold', fontsize=9)

plt.tight_layout()

# Create directory if it doesn't exist
os.makedirs('data/visualisation', exist_ok=True)

plt.savefig('data/visualisation/chart5_length.png', dpi=150, bbox_inches='tight')
